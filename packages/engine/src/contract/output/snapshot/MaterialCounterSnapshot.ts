/** Накопленные количества и стоимость по одному материалу. */
export interface MaterialCounterSnapshot {
  /** ID материала. */
  materialId: string;
  /** Произведено в микроединицах. */
  produced: number;
  /** Потреблено в микроединицах. */
  consumed: number;
  /** Принято рынком годного материала в микроединицах. */
  sold: number;
  /** Стоимость проданного материала в микроденежных единицах, строка. */
  soldCost: string;
  /** Списано в микроединицах. */
  scrapped: number;
  /** Стоимость списанного материала в микроденежных единицах, строка. */
  scrapCost: string;
}
