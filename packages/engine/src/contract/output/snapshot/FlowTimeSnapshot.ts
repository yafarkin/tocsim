/** Накопленное время прохождения и средние значения по известной истории. */
export interface FlowTimeSnapshot {
  /** Количество с известным началом отсчёта в микроединицах. */
  knownQuantity: number;
  /** Количество с неизвестным началом отсчёта в микроединицах. */
  unknownQuantity: number;
  /** Календарная сумма в микроединицах × мс, десятичная строка. */
  calendarQuantityMs: string;
  /** Рабочая сумма в микроединицах × мс, десятичная строка. */
  workQuantityMs: string;
  /** Среднее календарное время в мс или null при отсутствии известной истории. */
  meanCalendarMs: number | null;
  /** Среднее рабочее время в мс или null при отсутствии известной истории. */
  meanWorkMs: number | null;
}
