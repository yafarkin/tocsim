/** Выпуск и поставка одного конечного продукта. */
export interface ProductFlowReport {
  /** ID конечного материала. */
  materialId: string;
  /** Произведённое количество в микроединицах, строка. */
  produced: string;
  /** Принятое рынком количество в микроединицах, строка. */
  delivered: string;
  /** Произведённое, но ещё не принятое количество в микроединицах, строка. */
  awaitingAcceptance: string;
}
