/** Безразмерная доходность за период в виде точной дроби, не процент и не годовая ставка. */
export interface InvestmentRoi {
  /** Прибыль, умноженная на длительность; может быть отрицательной, строка. */
  numerator: string;
  /** Интеграл общих вложений в микроденежных единицах × мс, строка. */
  denominator: string;
}
