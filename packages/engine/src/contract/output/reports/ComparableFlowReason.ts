/** Причина, по которой нельзя построить общий сопоставимый поток, или null при совместимости. */
export type ComparableFlowReason =
  /** Рецепт требует несколько разных входных материалов. */
  | 'assembly'
  /** Рецепт изменяет количество материала. */
  | 'quantityChange'
  /** В сети несколько видов сырья или конечных продуктов. */
  | 'mixedProducts'
  /** Общий сопоставимый поток существует. */
  | null;
