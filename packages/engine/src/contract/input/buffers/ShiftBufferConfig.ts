/** Входной буфер, вместимость которого вычисляется от длительности рабочей смены. */
export interface ShiftBufferConfig {
  /** Признак вместимости, заданной долей смены. */
  kind: 'shift';
  /** Положительная доля смены в десятичной строке, максимум шесть знаков после точки. */
  shifts: string;
}
