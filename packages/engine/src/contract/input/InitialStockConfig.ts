/** Начальная физическая партия материала до запуска модели. */
export interface InitialStockConfig {
  /** Уникальный стабильный ID записи запаса. */
  id: string;
  /** ID поста-владельца или warehouse для общего сырьевого склада. */
  ownerId: string;
  /** Место хранения: общий склад, входной или выходной буфер поста. */
  location: 'warehouse' | 'input' | 'output';
  /** ID материала запаса. */
  materialId: string;
  /** Положительное количество в десятичной строке. */
  quantity: string;
  /** Полная стоимость записи в десятичной строке денежных единиц. */
  cost: string;
}
