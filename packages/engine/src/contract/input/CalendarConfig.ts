/** Календарь повторяющегося рабочего дня. Все времена задаются в миллисекундах от полуночи. */
export interface CalendarConfig {
  /** Начало рабочей смены, например 28 800 000 для 08:00. */
  shiftStartMs: number;
  /** Начало обеда; должно быть позже начала смены. */
  lunchStartMs: number;
  /** Конец обеда; должен быть позже его начала и раньше конца смены. */
  lunchEndMs: number;
  /** Конец рабочей смены в те же сутки; ночные смены не поддерживаются. */
  shiftEndMs: number;
}
