/** Плановое обслуживание после полной партии по времени обработки или числу повторений. */
export interface EnabledMaintenanceConfig {
  /** Обслуживание включено. */
  enabled: true;
  /** Длительность обслуживания в целых миллисекундах, не меньше 1. */
  durationMs: number;
  /** Необязательный порог суммарного времени обработки в миллисекундах; отсутствие поля отключает порог. */
  processingThresholdMs?: number;
  /** Необязательный порог завершённых повторений; одновременная партия учитывает все свои повторения. */
  repetitionsThreshold?: number;
}
