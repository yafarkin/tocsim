/** Материал, участвующий в производственной сети. */
export interface MaterialConfig {
  /** Уникальный стабильный ID из латинских букв, цифр, подчёркиваний и дефисов. */
  id: string;
  /** Отображаемое название; не влияет на расчёт. */
  name: string;
  /** Цвет для UI в текстовом формате; не влияет на расчёт. */
  color: string;
  /** raw — сырьё, intermediate — полуфабрикат, finished — конечный продукт. */
  role: 'raw' | 'intermediate' | 'finished';
  /** Закупочная цена в десятичной строке; обязательна для raw. */
  purchasePrice?: string;
  /** Цена продажи в десятичной строке; обязательна для finished. */
  salePrice?: string;
}
