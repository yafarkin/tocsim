/** Затраты и капитал поста в десятичных строках денежных единиц. */
export interface StationCostsConfig {
  /** Условно-постоянные затраты за полную рабочую смену. */
  perShift: string;
  /** Стоимость одного часа работы поста в общий обед. */
  perLunchHour: string;
  /** Вложенный капитал для инвестиционного отчёта. */
  capital: string;
}
