/** Источник сырья для производственной сети. */
export interface SourceConfig {
  /** Уникальный стабильный ID источника. */
  id: string;
  /** Отображаемое название; не влияет на расчёт. */
  name: string;
  /** ID поставляемого сырья. */
  materialId: string;
  /** virtual — неограниченное сырьё, warehouse — конечный общий склад. */
  availability: 'virtual' | 'warehouse';
  /** Положительное количество одной попытки поставки в десятичной строке. */
  quantity: string;
  /** Интервал между попытками поставки в целых миллисекундах, не меньше 1. */
  intervalMs: number;
}
