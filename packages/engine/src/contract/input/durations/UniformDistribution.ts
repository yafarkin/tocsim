/** Равномерное распределение длительности обработки. */
export interface UniformDistribution {
  /** Признак равномерного распределения. */
  kind: 'uniform';
  /** Минимальная длительность в целых миллисекундах, не меньше 1. */
  minMs: number;
  /** Максимальная длительность в целых миллисекундах, не меньше minMs. */
  maxMs: number;
}
