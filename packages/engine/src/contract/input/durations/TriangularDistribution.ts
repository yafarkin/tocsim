/** Треугольное распределение длительности обработки. */
export interface TriangularDistribution {
  /** Признак треугольного распределения. */
  kind: 'triangular';
  /** Минимальная длительность в целых миллисекундах, не меньше 1. */
  minMs: number;
  /** Наиболее вероятная длительность между minMs и maxMs включительно. */
  peakMs: number;
  /** Максимальная длительность в целых миллисекундах, не меньше minMs. */
  maxMs: number;
}
