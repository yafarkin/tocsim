/** Логнормальная длительность, заданная средним и коэффициентом вариации. */
export interface LognormalDistribution {
  /** Признак логнормального распределения. */
  kind: 'lognormal';
  /** Средняя длительность в миллисекундах, больше 0. */
  meanMs: number;
  /** Коэффициент вариации от 0 до 2; ноль даёт постоянную длительность. */
  cv: number;
}
