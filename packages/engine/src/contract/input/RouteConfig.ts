/** Направленный маршрут одного материала между источником, постами и рынком. */
export interface RouteConfig {
  /** Уникальный стабильный ID маршрута. */
  id: string;
  /** ID источника или поста-отправителя. */
  fromId: string;
  /** ID поста-получателя или зарезервированный ID market. */
  toId: string;
  /** ID перемещаемого материала. */
  materialId: string;
}
